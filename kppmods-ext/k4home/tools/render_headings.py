#!/usr/bin/env python3
"""Pre-render k4home's static headings with fun fonts.

KPP's text renderer can only use fonts the firmware knows, so the page title
(default "scribe home", Monocraft) and section headings (JetBrains Mono) are rendered to
grayscale+alpha PNGs here and shown as images. Writes assets/heading-*.png and
headings.gen.js (layout sizes; the Scribe draws ~1.8 device px per layout unit).

Usage: python3 tools/render_headings.py FONT_DIR [--title TEXT] [--title-px N]

The title defaults to "scribe home" at 80 px (Monocraft). Redeploy afterwards.
FONT_DIR needs Monocraft-Bold.ttf and JetBrainsMono-ExtraBold.ttf (both OFL:
github.com/IdreesInc/Monocraft, github.com/JetBrains/JetBrainsMono).
"""
import argparse
import json
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

PX_PER_UNIT = 1.8
HERE = Path(__file__).resolve().parent.parent
HEADINGS = {
    "title": ("scribe home", "Monocraft-Bold.ttf", 80),
    "books": ("BOOKS", "JetBrainsMono-ExtraBold.ttf", 44),
    "calendar": ("CALENDAR", "JetBrainsMono-ExtraBold.ttf", 44),
    "notebooks": ("NOTEBOOKS", "JetBrainsMono-ExtraBold.ttf", 44),
    "articles": ("ARTICLES", "JetBrainsMono-ExtraBold.ttf", 44),
    "uncategorized": ("UNCATEGORIZED", "JetBrainsMono-ExtraBold.ttf", 44),
}


def render(text, font_path, px):
    font = ImageFont.truetype(str(font_path), px)
    left, top, right, bottom = font.getbbox(text)
    pad = max(2, px // 12)
    width, height = right - left + 2 * pad, bottom - top + 2 * pad
    alpha = Image.new("L", (width, height), 0)
    ImageDraw.Draw(alpha).text((pad - left, pad - top), text, font=font, fill=255)
    image = Image.new("LA", (width, height), (0, 0))
    image.putalpha(alpha)
    return image


def main():
    parser = argparse.ArgumentParser(description="Pre-render k4home's headings.")
    parser.add_argument("fonts", help="folder with Monocraft-Bold.ttf and JetBrainsMono-ExtraBold.ttf")
    parser.add_argument("--title", help="page title text (default: %(default)s)", default=HEADINGS["title"][0])
    parser.add_argument("--title-px", type=int, default=HEADINGS["title"][2], help="title font size in px (default: %(default)s)")
    args = parser.parse_args()
    fonts = Path(args.fonts)
    HEADINGS["title"] = (args.title, HEADINGS["title"][1], args.title_px)
    sizes = {}
    for key, (text, font, px) in HEADINGS.items():
        image = render(text, fonts / font, px)
        name = f"heading-{key}.png"
        image.save(HERE / "assets" / name, optimize=True)
        sizes[key] = {
            "path": f"assets/{name}",
            "width": round(image.width / PX_PER_UNIT, 1),
            "height": round(image.height / PX_PER_UNIT, 1),
            "label": text,
        }
        print(f"{name}: {image.width}x{image.height}px")
    (HERE / "headings.gen.js").write_text(
        "// Generated by tools/render_headings.py; do not edit.\n"
        f"export const HEADINGS = {json.dumps(sizes, indent=2)};\n"
    )


if __name__ == "__main__":
    main()
